export function PackageExports() {
  const missing = Object.entries(components)
    .filter(([, value]) => value === undefined)
    .map(([name]) => name);
  return (
    <output data-testid="package-exports">
      {missing.length
        ? `Missing: ${missing.join(', ')}`
        : `${Object.keys(components).length} runtime exports available`}
    </output>
  );
}

